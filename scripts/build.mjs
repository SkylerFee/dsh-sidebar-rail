#!/usr/bin/env node
/**
 * 构建发布入口：lib/index.js（空 Host 入口）与 lib/client.js（宿主可直接加载的静态模块）。
 *
 * 设计要点（见 docs/adr/0006）：
 *   - esbuild 只做转换与打包，类型检查由 `tsc --noEmit` 单独负责；
 *   - client 打成 CJS 后包进 `window.__ModuleLoader__.load({ id, factory })`，
 *     工厂拿到宿主的 `require`，因此 React 不会被私有打包进产物；
 *   - CSS 由 esbuild 的 text loader 作为字符串注入产物，仍由插件的 `apply`
 *     effect 创建 style 并在卸载时移除；
 *   - `lib/` 是生成目录，不提交 Git。
 *
 * 用法：
 *   node scripts/build.mjs            一次性构建并自检
 *   node scripts/build.mjs --watch    监听 src/ 持续重建（Ctrl-C 退出并释放 watcher）
 */
import { build, context } from 'esbuild'
import { mkdir, rm, writeFile } from 'node:fs/promises'
import { readFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const outdir = join(root, 'lib')
const watch = process.argv.includes('--watch')

/**
 * 读取包名，作为 ModuleLoader 注册 id。
 *
 * 宿主按完整包名查找客户端工厂，因此 id 必须来自包元数据而不是硬编码，
 * 否则改名后注册与查找会静默错位。
 * @returns 包名。
 */
function packageName() {
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'))
  if (typeof pkg.name !== 'string' || pkg.name === '') {
    throw new Error('package.json has no name; the ModuleLoader id would be undefined')
  }
  return pkg.name
}

/** client 打包配置：单份静态脚本，不拆 chunk、不做动态 import。 */
const clientOptions = {
  entryPoints: [join(root, 'src/client/index.tsx')],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: ['es2022'],
  // JSX 走 classic 转换，运行期只请求宿主已有的 react / react-dom，
  // 不额外引入 react/jsx-runtime。
  jsx: 'transform',
  jsxFactory: 'h',
  jsxFragment: 'Fragment',
  // CSS 作为文本进入产物。
  loader: { '.css': 'text' },
  // 宿主在工厂里注入这两个模块，构建期不解析、不打包。
  external: ['react', 'react-dom'],
  define: { 'process.env.NODE_ENV': '"production"' },
  write: false,
  logLevel: 'warning',
}

/**
 * 把 client 的 CJS 输出包进 ModuleLoader 协议。
 *
 * 包装里的 `module` / `exports` 是工厂局部变量：注册阶段只声明工厂，
 * 不执行任何插件副作用（不读 React、DOM 或 localStorage）。
 * @param bundleText - esbuild 产出的 CJS 文本（导出 `{ inject, apply }`）。
 * @param id - ModuleLoader 注册 id（完整包名）。
 * @returns 可直接由宿主加载的静态脚本文本。
 */
function wrapClient(bundleText, id) {
  return [
    '/**',
    ' * dsh-sidebar-rail — Client half (generated by scripts/build.mjs; do not edit).',
    ' *',
    ' * Adds the icon rail macOS Desktop otherwise lacks. The plugin is additive: the',
    ' * shipped sidebar is never replaced, so search, view options, add-workspace, the',
    ' * settings seat and the account menu all stay shipped behavior.',
    ' *',
    ' * 由 src/client/ 构建而来；行为改动请改源码后重新构建。协议要求：注册阶段',
    ' * 只登记工厂，不触碰 React / DOM / localStorage。',
    ' */',
    'window.__ModuleLoader__.load({',
    `  id: ${JSON.stringify(id)},`,
    '  factory(require) {',
    '    const module = { exports: {} }',
    '    const exports = module.exports',
    '    ;(function (module, exports) {',
    bundleText.replace(/^/gm, '      ').trimEnd(),
    '    })(module, exports)',
    '    return module.exports',
    '  },',
    '})',
    '',
  ].join('\n')
}

/**
 * 检查打包文本是否满足加载协议。
 *
 * 宿主把 `./client` 指向的文件当静态脚本执行，因此不能留下顶层 ESM 语法，
 * 也不能出现相对路径的 `require`（那意味着有 chunk 逃出了单文件夹具）。
 * @param bundleText - esbuild 产出的 CJS 文本。
 * @returns 无；违反协议时抛错。
 */
function assertProtocol(bundleText) {
  if (/^\s*(?:import|export)\s/m.test(bundleText)) {
    throw new Error('client bundle contains top-level ESM syntax; the loader executes it as a static script')
  }
  if (/require\(\s*["']\.\.?\//.test(bundleText)) {
    throw new Error('client bundle contains a relative require; the loader only accepts single-file bundles')
  }
  const requests = new Set([...bundleText.matchAll(/require\(\s*["']([^"']+)["']\s*\)/g)].map((m) => m[1]))
  for (const request of requests) {
    if (request !== 'react' && request !== 'react-dom') {
      throw new Error(`client bundle requires "${request}"; only react and react-dom may come from the host`)
    }
  }
}

/**
 * 构建 Host 入口：保留空的 `apply` 导出，让 bundle 有可安装的一行。
 * @returns esbuild 输出文本。
 */
async function buildHost() {
  const result = await build({
    entryPoints: [join(root, 'src/index.ts')],
    bundle: false,
    format: 'esm',
    platform: 'neutral',
    target: ['es2022'],
    write: false,
    logLevel: 'warning',
  })
  const file = result.outputFiles?.[0]
  if (file === undefined) throw new Error('host entry produced no output')
  return file.text
}

/**
 * 构建 Client 入口并检查协议要求。
 * @param id - ModuleLoader 注册 id。
 * @returns 可直接加载的客户端脚本文本。
 */
async function buildClient(id) {
  const result = await build(clientOptions)
  const file = result.outputFiles?.[0]
  if (file === undefined) throw new Error('client entry produced no output')
  assertProtocol(file.text)
  return wrapClient(file.text, id)
}

/**
 * 写出两个入口。
 * @param hostText - Host 入口文本。
 * @param clientText - Client 入口文本。
 * @returns 无。
 */
async function writeOutputs(hostText, clientText) {
  await mkdir(outdir, { recursive: true })
  await writeFile(join(outdir, 'index.js'), hostText, 'utf8')
  await writeFile(join(outdir, 'client.js'), clientText, 'utf8')
}

/** 一次性构建：先清空生成目录，避免旧产物残留成「引用存在而文件缺失」。 */
async function buildOnce() {
  const id = packageName()
  await rm(outdir, { recursive: true, force: true })
  const [hostText, clientText] = await Promise.all([buildHost(), buildClient(id)])
  await writeOutputs(hostText, clientText)
  console.log(`built lib/index.js and lib/client.js for ${id}`)
}

/**
 * 监听模式：增量重建两个入口，退出时释放 watcher 与 esbuild context。
 * @returns 无。
 */
async function buildWatch() {
  const id = packageName()
  await mkdir(outdir, { recursive: true })
  const hostContext = await context({
    entryPoints: [join(root, 'src/index.ts')],
    bundle: false,
    format: 'esm',
    platform: 'neutral',
    target: ['es2022'],
    outfile: join(outdir, 'index.js'),
    logLevel: 'warning',
  })
  await hostContext.watch()
  // client 需要包装后再落盘，所以走回调式重建，而不是让 esbuild 直接写文件。
  const rebuildClient = async () => {
    const result = await build(clientOptions)
    const file = result.outputFiles?.[0]
    if (file === undefined) return
    assertProtocol(file.text)
    await writeFile(join(outdir, 'client.js'), wrapClient(file.text, id), 'utf8')
    console.log('rebuilt lib/client.js')
  }
  await rebuildClient()
  const { watch: watchFs } = await import('node:fs')
  const watcher = watchFs(join(root, 'src'), { recursive: true }, (_event, filename) => {
    if (filename !== null && (filename.endsWith('.css') || filename.endsWith('.json'))) return
    rebuildClient().catch((error) => {
      console.error('[dsh-sidebar-rail] client rebuild failed', error)
    })
  })
  /** 释放 watcher 与 esbuild context，避免 Ctrl-C 后留下句柄。 */
  const shutdown = async () => {
    watcher.close()
    await hostContext.dispose()
    process.exit(0)
  }
  process.on('SIGINT', shutdown)
  process.on('SIGTERM', shutdown)
  console.log('watching src/ — press Ctrl-C to stop')
}

if (watch) {
  await buildWatch()
} else {
  await buildOnce()
}
